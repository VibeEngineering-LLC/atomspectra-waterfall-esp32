#pragma once

#include <stdbool.h>
#include <stdint.h>

// #FW-2/#FW-3: поведение прошивки при старте платы (persist в NVS, namespace "boot").
// Все флаги по умолчанию false — из коробки ничего не запускается и не чистится
// (решение оператора 2026-06-29). Пользователь включает галочки один раз в Web UI
// (страница «Система» → «Поведение при старте платы»); значения переживают
// ребут / OTA / safe-mode.
// #FW-42: длина буфера префикса имён экспортов (23 значащих символа + '\0').
#define BOOT_NAME_PREFIX_CAP 24

// issue #52: пределы автоматических резервных снимков спектра.
#define BOOT_BACKUP_KEEP_MAX   20      // 20 x 33 КБ = 660 КБ на 12,9-МБ разделе
#define BOOT_BACKUP_HOURS_MIN  1
#define BOOT_BACKUP_HOURS_MAX  168     // неделя

typedef struct {
    bool autostart_spectrum;    // на первом USB-коннекте после ребута послать -sta (набор спектра)
    bool autostart_waterfall;   // на первом USB-коннекте начать запись водопада (spectrogram_start + -sta)
    bool clear_spectrum;        // при старте очистить накопленный спектр (ESP spectrum_reset + -rst прибору)
    bool clear_waterfall;       // при старте очистить водопад (spectrogram_clear)
    // #FW-42: префикс имени во всех экспортах (spectrum/waterfall/backup), чтобы не
    // путались файлы от разных детекторов (пример: "MY1"→"MY1spectrum.csv"). Пустая
    // строка = историческое поведение (без префикса). Санитизируется до [A-Za-z0-9_-].
    char name_prefix[BOOT_NAME_PREFIX_CAP];
    // issue #52: автоматические резервные снимки спектра в /storage/bk.
    uint8_t  backup_keep;         // X: сколько снимков хранить, 0 = выключено (дефолт)
    uint16_t backup_hours;        // Y: период между снимками, часы (дефолт 24)
    bool     backup_test_minutes; // Y читать как МИНУТЫ — только для стенда, в UI нет
    // AWF-2a настройка (решение оператора 25.09, финал): «Переходить в
    // полевую точку доступа при потере Wi-Fi». ИСКЛЮЧЕНИЕ из конвенции этого
    // файла «все флаги по умолчанию false = старое поведение»: здесь ключ
    // ПОЛОЖИТЕЛЬНЫЙ (не disabled) — отсутствующий в NVS ключ (апгрейд со
    // старой прошивки, где этой настройки не было вовсе) обязан дать ВЫКЛ,
    // а не ВКЛ. Прежний инвертированный `fap_dis` (missing→ВКЛ) на реальных
    // платах не встречается — существовал только в этой ветке до релиза,
    // переименован без миграции. Страховка (STA без IP 300с → Field AP)
    // не зависит от этого флага и остаётся при ВЫКЛ.
    bool     field_ap_fallback_enabled;
} boot_config_t;

// Читает конфиг из NVS. Любой отсутствующий ключ → false / "". Безопасно вызывать
// после nvs_flash_init() (выполняется в wifi_manager_init на boot).
void boot_config_load(boot_config_t *out);

// Пишет конфиг в NVS (namespace "boot"). name_prefix санитизируется тут (в NVS
// попадают только символы [A-Za-z0-9_-], усечение до BOOT_NAME_PREFIX_CAP-1).
// Возвращает 0 при успехе, -1 при ошибке.
int  boot_config_save(const boot_config_t *in);

// issue #52: номер сессии платы. Инкрементируется РОВНО ОДИН раз за загрузку —
// вызывать из app_main до старта задач, а не из обработчиков. Имя снимка несёт
// этот номер, поэтому после пропадания питания новые снимки не смешиваются со
// старыми, а человеку ничего переключать не нужно.
// Хранится отдельным ключом и boot_config_save() НЕ трогает: сохранение настроек
// из Web UI не должно сбивать нумерацию.
// `floor_value` — номер, ниже которого сессия быть не может (обычно наибольший
// номер сессии среди уже лежащих на flash снимков, см. spectrum_backup_max_session).
// Нужен потому, что NVS стирается штатным восстановлением IDF при
// ESP_ERR_NVS_NO_FREE_PAGES: счётчик начался бы с 1 поверх снимков сессии 9, и
// ротация (порядок по номеру сессии) удаляла бы именно новые снимки.
// Возвращает 0, если NVS недоступен — вызывающий обязан это отличить: при 0
// снимки делать нельзя, иначе они молча перезапишут снимки прошлой загрузки.
uint32_t boot_config_bump_session(uint32_t floor_value);

// Текущий номер сессии (0, если bump ещё не вызывался и ключа в NVS нет).
uint32_t boot_config_get_session(void);
